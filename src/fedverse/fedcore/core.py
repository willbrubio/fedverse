def attach_meta(metric_df, md, id_col):
    """
    Attaches cropped bandit metadata dataframe to the aggragated bandit metric dataframe

    Arguments:
        metric_df; Dataframe
            Dataframe containing aggragated metrics for multiple mice in a multiple assay types by a FED device
        md; Dataframe
            meta dataframe that contatins cropped bandit key created by build_bandit_metakey
        id_col; String, default "Mouse_ID"
            String detailing what column will serve as the key column   
    Returns:
        bm_md; Dataframe    
            Dataframe containing aggregated metrics with metadata
    """

    status.step("Attaching metadata to metrics")
    df = metric_df.copy()

    # catch instances where the filename column may be "File" instead of "filename"
    if "File" in df.columns:
        df["filename"] = df["File"].astype(str).map(_basename)


    if "filename" in md.columns and "Mouse_ID" in md.columns:
        mouse_map = md.dropna(subset=["filename"]).drop_duplicates("filename").set_index("filename")["Mouse_ID"]
        df["Mouse_ID"] = df["filename"].map(mouse_map)

        # attempt to fill missing mouse ID's
        if df["Mouse_ID"].isna().any():
            # find known ids
            known_ids = md["Mouse_ID"].dropna().unique().tolist()
            # iterate over empty id's
            for i, r in df.loc[df["Mouse_ID"].isna()].iterrows():
                base = _file_base_lower(r["filename"])
                hits = [mid for mid in known_ids if str(mid).lower() in base]
                if len(hits) == 1:
                    df.at[i, "Mouse_ID"] = hits[0]
                elif len(hits) > 1:
                    longest = max(len(str(h)) for h in hits)
                    best = [h for h in hits if len(str(h)) == longest]
                    if len(best) == 1:
                        df.at[i, "Mouse_ID"] = best[0]

    # check if the id_col is mouse_id and if both dataframes have a mouse_id column and if the mouse_id column in the metric dataframe has any non-null values
    if (id_col == "Mouse_ID") and ("Mouse_ID" in df.columns) and ("Mouse_ID" in md.columns) and df["Mouse_ID"].notna().any():
        md_unique = md.drop_duplicates(subset=["Mouse_ID"], keep="first")
        df_md = df.merge(md_unique, on="Mouse_ID", how="left", suffixes=("", "_md"))
    else:
        if "filename" not in md.columns:
            raise ValueError("metadata_df has no 'filename' column, but filename is needed for this mode.")
        md_unique = md.drop_duplicates(subset=["filename"], keep="first")
        df_md = df.merge(md_unique, on="filename", how="left", suffixes=("", "_md"))

    status.ok("metadata attached")
    status.preview(df_md, msg="merged metric dataframe")

    return df_md


