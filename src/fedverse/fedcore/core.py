def output_l3(df_md, id_col, other_id, meta_cols, root_path, assay = None, resolve_hom_hemi = True):
    """
    Arguemnts:
        df_md; Dataframe
            Dataframe containing aggregated metrics with metadata
        id_col; string
            String detailing what column will serve as the key column to link both metadata and metric files
        other_id; string
            String detailing fallback key column to link metadata and metrics dataframes
        meta_cols; List
            list of columns we are interested in outputing to the L3
        assay; str
            a strong defining what assays L3 should be output
        resolve_hom_hemi; bool, default True
            If True, the L3 file written to disk resolves ambiguous "Hom/Hemi" Genotype
            labels to "Hom" or "Hemi" using Sex (Female -> Hom, Male -> Hemi). If False
            (i.e., resolve_hom_hemi=False), "Hom/Hemi" is written out as-is. The returned dataframe always
            keeps "Hom/Hemi" unresolved regardless of this setting.
    """

    status.step("Preparing L3")

    # prepare the L3 Directory for population
    status.sub("Creating L3 directory")

    out_dir = Path(root_path,)
    out_dir.mkdir(parents=True, exist_ok=True)

    status.ok("L3 directory created")

    df = df_md.copy()

    # get metric columns based on assay type
    metric_cols = get_cols(assay, "metric", status)

    # check for agreement between columns in metric file and columns specified
    metric_cols = [c for c in metric_cols if c in df.columns]


    if "Session_type" in df.columns:
        session_series = df["Session_type"].astype(str).str.strip()
    else:
        status.warn("'Session_type' column not found in metric file")
        sess_map = {
            core._basename(getattr(_sessions[i], "name", f"File_{i}")):
            (_sessions[i].attrs.get("Session_type") or "Unknown")
            for i in range(len(_sessions))
        }
        session_series = df["filename"].map(sess_map).fillna("Unknown").astype(str)

    session_series = session_series.str.replace(r"\s+", "_", regex=True)
    df["_Session_type_for_csv"] = session_series

   

    df_merged = df.copy()
    metric_csv = with_session_suffix_for_csv(df_merged, metric_cols)



    ### Prepare final export columns
    def _metric_match(col: str) -> bool:
        return any(col.startswith(base + "_") for base in metric_cols)

    metric_keep = [c for c in metric_csv.columns if _metric_match(c)]
    if not metric_keep:
        raise RuntimeError("No session-suffixed metric columns matched; check 'metric_cols'.")

    meta_keep = [c for c in meta_cols if c in metric_csv.columns]

    drop_cols = []
    if other_id in metric_csv.columns:
        drop_cols.append(other_id)
    for c in ["File", "FileIndex"]:
        if c in metric_csv.columns:
            drop_cols.append(c)

    metric_csv = metric_csv.drop(columns=drop_cols, errors="ignore")

    cols_out = [id_col] + meta_keep + metric_keep
    cols_out = [c for c in cols_out if c in metric_csv.columns]
    metric_csv = metric_csv.loc[:, cols_out].copy()

    # Resolve ambiguous Hom/Hemi genotype labels using Sex (Female -> Hom, Male -> Hemi)
    # Applied only to the CSV export; the returned dataframe keeps "Hom/Hemi" as-is.
    if resolve_hom_hemi and "Genotype" in metric_csv.columns and "Sex" in metric_csv.columns:
        ambiguous = metric_csv["Genotype"].astype(str).str.lower() == "hom/hemi"
        if ambiguous.any():
            is_female = metric_csv.loc[ambiguous, "Sex"].astype(str).str.lower().str.startswith("f")
            metric_csv.loc[ambiguous, "Genotype"] = is_female.map({True: "Hom", False: "Hemi"})

    ### get name of file ###
    example = df_merged.iloc[0]

    strain_name = str(example.get("Gene", example.get("Strain", "NA"))).replace(" ", "_")
    strain_num_raw = example.get("Gene_ID", example.get("Strain_ID", "NA"))
    try:
        strain_num = f"{int(strain_num_raw):03d}"
    except Exception:
        strain_num = str(strain_num_raw).zfill(3)

    task_name = str(example.get("Session_type", "Unknown")).replace(" ", "_")
    fname = f"{strain_name}_{strain_num}_{task_name}_L3.csv"

    # Return 
    status.ok("L3 prepared")
    status.preview(df_md, msg="L3 Dataframe")

    out_path = out_dir / fname
    metric_csv_out.to_csv(out_path, index=False)

    return(metric_csv)







