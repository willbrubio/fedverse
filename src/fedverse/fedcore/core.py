# functions need for reading in cleaned FED files
def extract_session_type(csv_path, fallback="Unknown"):
    """
    Read 'Session_Type ' or variants; return first non-empty value.
    Called by: 
        ingest_l1
    Argument:
        csv_path - has to be a pathway to a csv within a zipped file
    """
    try:
        # Read in the individual file
        df = pd.read_csv(csv_path, sep=None, engine='python', dtype=str)
        # isolate columns names 
        df.columns = [c.strip() for c in df.columns]
        lower = {c.casefold(): c for c in df.columns}
        # Loop through column names to locate the session column
        for cand in ["session_type", "session type", "sessiontype", "session"]:
            if cand in lower:
                col = lower[cand]
                vals = df[col].dropna().astype(str).str.strip()
                vals = vals[vals.ne("")]
                if not vals.empty:
                    # Return the first value of the session-like column
                    return vals.iloc[0]
    except Exception:
        pass
    return fallback


def ingest_l1(l1_path):
    """
    Define a function that will ingest data derived from a zipped folder contating fed data
    Argument: 
        l1_path - is required to be a path to a zipped folder that contains processed data from a fed. 
    """
    status.step("Beginning Ingest") 
    # check if the path is a zip file else pass error
    if not zipfile.is_zipfile(l1_path):
        raise ValueError(f"RAW_PATH must be a zip archive: {l1_path}")

    # define lists to populate
    fed_list, loaded_files, session_types = [], [], []

    # Create a empty list to catch error messages
    errors = []
    
    # pathify the name and create dictionary
    l1_path = Path(l1_path)
    uploaded = {l1_path.name: l1_path.read_bytes()}

    # iteracte through the dictionary
    for name, data in uploaded.items():
        ### for ZIP files
        if name.lower().endswith(".zip"):
            with zipfile.ZipFile(io.BytesIO(data)) as zf:
                for zi in zf.infolist():
                    if not zi.filename.lower().endswith(".csv"):
                        continue
                    file_data = zf.read(zi)
                    # if the file is short remove the file
                    if len(file_data) <= 1024:
                        continue
                    with tempfile.NamedTemporaryFile(mode="w+b", suffix=".csv", delete=False) as tmp:
                        tmp.write(file_data); tmp_path = tmp.name
                    # attempt to populate lists
                    try:
                        session_type = extract_session_type(tmp_path)
                        # try to open on basic datetime else try beam index
                        try:
                            df = fed3_loading.load(tmp_path)
                        except Exception as e:
                            df = fed3_loading.load(tmp_path, index_col="datetime")

                        df.name = os.path.basename(zi.filename)
                        df.attrs = {"Session_type": session_type}
                        fed_list.append(df)
                        loaded_files.append(os.path.basename(zi.filename))
                        session_types.append(session_type)
                    except Exception as e:
                        errors.append(f"Error loading {zi.filename}: {e}")
                    finally:
                        os.remove(tmp_path)
        ### if a csv file happens to be uploaded
        elif name.lower().endswith(".csv"):
            if len(data) <= 1024:
                continue
            with tempfile.NamedTemporaryFile(mode="w+b", suffix=".csv", delete=False) as tmp:
                tmp.write(data); tmp_path = tmp.name
            try:
                session_type = extract_session_type(tmp_path)

                # try to open on basic datetime else try beam index
                try:
                    df = fed3_loading.load(tmp_path)
                except Exception:
                    df = fed3_loading.load(tmp_path, index_col="datetime")

                df.name = os.path.basename(name)
                df.attrs = {"Session_type": session_type}
                fed_list.append(df)
                loaded_files.append(os.path.basename(name))
                session_types.append(session_type)
            except Exception as e:
                errors.append(f"Error loading {name}: {e}")
            finally:
                os.remove(tmp_path)

    # if any errors occoured return the errors
    if errors:
        print()
        for err in errors:
            status.warn(err)
    
    status.ok(f"Ingest Complete - Loaded {len(loaded_files)} files. Session types captured for all.")

    # ensure that a datetime column exists
    for df in fed_list:
        has_col = 'MM:DD:YYYY hh:mm:ss' in df.columns or 'datetime' in df.columns
        if not has_col and df.index.name in ('MM:DD:YYYY hh:mm:ss', 'datetime'):
            df[df.index.name] = df.index
            df.index.name = None

        has_ts = 'MM:DD:YYYY hh:mm:ss' in df.columns or 'datetime' in df.columns
        print(f"{df.name}: timestamp column present = {has_ts}")

    # return three lists
    return fed_list, loaded_files, session_types

