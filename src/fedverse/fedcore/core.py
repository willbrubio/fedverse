def _stats_text(dfm, x_label, hue_label, *, mode="ref", ref_group=None, pair_list=None):
    df = dfm.dropna(subset=["value"]).copy()
    g_n = df["XGroup"].nunique(dropna=True)
    h_n = df["HueGroup"].nunique(dropna=True)

    if mode == "pairs" and pair_list:
        lines = ["Selected pairwise ANOVA tests:"]
        for a,b in pair_list:
            sub = df[df["XGroup"].isin([a,b])]
            res = _anova_subset(sub)
            if not res["ok"]:
                lines.append(f"{a} vs {b}: {res['err'] or 'failed'}"); continue
            if res["n_h"] >= 2:
                lines.append(
                    f"{a} vs {b} (Two-way: {x_label}, {hue_label})  "
                    f"{x_label}: {_fmt_p(res['p_x'])} | {hue_label}: {_fmt_p(res['p_h'])} | "
                    f"{x_label}×{hue_label}: {_fmt_p(res['p_int'])}"
                )
            else:
                lines.append(f"{a} vs {b} (One-way {x_label}): {_fmt_p(res['p_x'])}")
        return "\n".join(lines)

    def fmt(p): return _fmt_p(p)
    if g_n == 2 and h_n <= 1:
        g1, g2 = sorted(df["XGroup"].unique())
        v1 = df[df["XGroup"] == g1]["value"].dropna()
        v2 = df[df["XGroup"] == g2]["value"].dropna()
        if len(v1) > 1 and len(v2) > 1:
            p = _pg_get_pval(pg.ttest(v1, v2, paired=False))
            ### Alternative p-value call ###
            # p = _safe_ttest_p(v1, v2, paired=False)
            return f"t-test ({x_label}): {fmt(p)}\n{g1} vs {g2}"
        return "t-test: not enough data"

    if g_n >= 2 and h_n >= 2:
        try:
            model = ols('value ~ C(XGroup) + C(HueGroup) + C(XGroup):C(HueGroup)', data=df).fit()
            an = sm.stats.anova_lm(model, typ=2)
            return (
                "Two-way ANOVA\n"
                f"{x_label}: {fmt(float(an.loc['C(XGroup)','PR(>F)']))}\n"
                f"{hue_label}: {fmt(float(an.loc['C(HueGroup)','PR(>F)']))}\n"
                f"{x_label}×{hue_label}: {fmt(float(an.loc['C(XGroup):C(HueGroup)','PR(>F)']))}"
            )
        except Exception as e:
            return f"ANOVA failed: {e}"

    if g_n >= 2:
        try:
            model = ols('value ~ C(XGroup)', data=df).fit()
            return f"One-way ANOVA ({x_label}): {fmt(float(model.f_pvalue))}"
        except Exception as e:
            return f"One-way ANOVA failed: {e}"
    return "Too few groups for stats"



def _twoway_anova_full(df):
    """
    Returns dict with full ANOVA stats including df for F.
    If HueGroup has <2 levels -> one-way (XGroup only).
    """
    d = df.dropna(subset=["value","XGroup"]).copy()
    if d.empty or d["XGroup"].nunique() < 2:
        return {"ok": False, "err": "Too few groups"}

    n_h = d["HueGroup"].nunique(dropna=True) if "HueGroup" in d.columns else 0

    try:
        if n_h >= 2:
            model = ols("value ~ C(XGroup) + C(HueGroup) + C(XGroup):C(HueGroup)", data=d).fit()
            an = sm.stats.anova_lm(model, typ=2)

            residual_row = "Residual"
            ss_error = float(an.loc[residual_row, "sum_sq"])
            df_den = int(an.loc[residual_row, "df"])

            ss_x = float(an.loc["C(XGroup)", "sum_sq"])
            ss_h = float(an.loc["C(HueGroup)", "sum_sq"])
            ss_int = float(
                an.loc["C(XGroup):C(HueGroup)", "sum_sq"]
            )

            eta_p_x = (
                ss_x / (ss_x + ss_error)
                if (ss_x + ss_error) > 0
                else np.nan
            )

            eta_p_h = (
                ss_h / (ss_h + ss_error)
                if (ss_h + ss_error) > 0
                else np.nan
            )

            eta_p_int = (
                ss_int / (ss_int + ss_error)
                if (ss_int + ss_error) > 0
                else np.nan
            )

            return {
                "ok": True,
                "test": "Two-way ANOVA",

                "F_x": float(an.loc["C(XGroup)", "F"]),
                "df_x_num": int(an.loc["C(XGroup)", "df"]),
                "df_x_den": df_den,
                "p_x": float(an.loc["C(XGroup)", "PR(>F)"]),
                "ss_x": ss_x,
                "eta_p_x": eta_p_x,

                "F_h": float(an.loc["C(HueGroup)", "F"]),
                "df_h_num": int(an.loc["C(HueGroup)", "df"]),
                "df_h_den": df_den,
                "p_h": float(an.loc["C(HueGroup)", "PR(>F)"]),
                "ss_h": ss_h,
                "eta_p_h": eta_p_h,

                "F_int": float(an.loc["C(XGroup):C(HueGroup)", "F"]),
                "df_int_num": int(an.loc["C(XGroup):C(HueGroup)", "df"]),
                "df_int_den": df_den,
                "p_int": float(an.loc["C(XGroup):C(HueGroup)", "PR(>F)"]),
                "ss_int": ss_int,
                "eta_p_int": eta_p_int,
                "ss_error": ss_error,
            }

        else:
            model = ols("value ~ C(XGroup)", data=d).fit()
            an = sm.stats.anova_lm(model, typ=2)

            ss_x = float(an.loc["C(XGroup)", "sum_sq"])
            ss_error = float(an.loc["Residual", "sum_sq"])

            eta_p_x = (
                ss_x / (ss_x + ss_error)
                if (ss_x + ss_error) > 0
                else np.nan
            )

            return {
                "ok": True,
                "test": "One-way ANOVA",
                "F_x": float(an.loc["C(XGroup)", "F"]),
                "df_x_num": int(an.loc["C(XGroup)", "df"]),
                "df_x_den": int(an.loc["Residual", "df"]),
                "p_x": float(an.loc["C(XGroup)", "PR(>F)"]),
                "ss_x": ss_x,
                "eta_p_x": eta_p_x,
                "ss_error": ss_error,
            }

    except Exception as e:
        return {"ok": False, "err": str(e)}


def _subjects_n_per_group(dfm):
    # n per XGroup (counts non-NaN values)
    n_per_x = dfm.groupby("XGroup")["value"].apply(lambda s: int(s.dropna().shape[0]))
    groups = _order_x_groups(dfm["XGroup"].dropna().unique().tolist())
    parts = [f"{g}: n={n_per_x.get(g, 0)}" for g in groups]
    return " | ".join(parts)


def _posthoc_ref_ttests(dfm, ref_group):
    d = dfm.dropna(subset=["value","XGroup"]).copy()
    ref = d[d["XGroup"] == ref_group]["value"].dropna().to_numpy()
    if ref_group is None or ref_group not in d["XGroup"].unique():
        return "n/a"

    groups = [g for g in d["XGroup"].unique().tolist() if g != ref_group]
    lines = []
    for g in _order_x_groups(groups):
        vals = d[d["XGroup"] == g]["value"].dropna().to_numpy()
        if len(vals) < 2 or len(ref) < 2:
            lines.append(f"{g} vs {ref_group}: not enough data")
            continue
        try:
            p = _pg_get_pval(pg.ttest(vals, ref, paired=False))
        except Exception:
            p = np.nan
        lines.append(f"{g} vs {ref_group}: p={_fmt_p_num(p)} {_p_to_stars(p)}")
    return " | ".join(lines) if lines else "n/a"


def _posthoc_pairs_anova(dfm, pair_list, x_label, hue_label):
    if not pair_list:
        return "n/a"
    lines = []
    for a, b in pair_list:
        sub = dfm[dfm["XGroup"].isin([a, b])].dropna(subset=["value"])
        if sub["XGroup"].nunique() < 2:
            continue
        res = _anova_subset(sub)  # uses existing helper (p only)
        if not res["ok"]:
            lines.append(f"{a} vs {b}: {res['err'] or 'failed'}")
            continue
        if res["n_h"] >= 2:
            lines.append(
                f"{a} vs {b}: {x_label} p={_fmt_p_num(res['p_x'])} {_p_to_stars(res['p_x'])}, "
                f"{hue_label} p={_fmt_p_num(res['p_h'])}, int p={_fmt_p_num(res['p_int'])}"
            )
        else:
            lines.append(f"{a} vs {b}: p={_fmt_p_num(res['p_x'])} {_p_to_stars(res['p_x'])}")
    return " | ".join(lines) if lines else "n/a"


def _fmt_eta_p2(value):
    """
    Format partial eta squared to three decimal places.
    """
    try:
        value = float(value)
    except (TypeError, ValueError):
        return "n/a"

    if not np.isfinite(value):
        return "n/a"

    return f"{value:.3f}"










def build_stats_table(long_df, ordered_x, root_path, mode = "ref", 
                      assay = None, ref_group=None, pair_list=None):
    """
    Arguments:
        long_df : Dataframe
            melted dataframe in a long format
        ordered : List
            List of genotypes that will be tested against eachother
        root_path : Path
            Path to the root directory where the stats table will be saved
    """

    status.step("Building Stats Table")

    # Create the directory that will be writen to
    out_dir = Path(root_path, "stats_table")
    out_dir.mkdir(parents=True, exist_ok=True)
    
    # get metric columns
    metric_cols = get_cols(assay, "metric", status)

    # get the groupings for which stats will be conducted
    sel_x = ordered_x

    
    ### Define Dictionaries to control tests dome
    # check for hemi genotypes and warn user that stats will be conducted with hemi groups
    # we need to conduct post hoc tests to account for hemi groups
    # and the stats will be divided into two groups by sex to account for the hemi groups
    # Male: WT x HEMI
    # Female: WT x HET & WT x HOM

    hemi_match = [geno for geno in sel_x if 'hemi' in geno.lower()]
    ref = ref_group or "WT"

    affected = "HOM/HEMI"   # merged X-linked group; Sex separates Hom(F) from Hemi(M)

    if hemi_match:
        status.warn("'hemi' genotype detected: running pooled + sex-split post hocs")
        test_dict = {
            "pooled":     {"filter": {},                                           "test_mode": "ref", "ref_grp": ref},
            "male_hemi":  {"filter": {"HueGroup": "M", "XGroup": [ref, affected]}, "test_mode": "pairs", "ref_grp": ref},
            "female_hom": {"filter": {"HueGroup": "F", "XGroup": [ref, affected]}, "test_mode": "pairs", "ref_grp": ref},
            "female_het": {"filter": {"HueGroup": "F", "XGroup": [ref, "HET"]},    "test_mode": "pairs", "ref_grp": ref},
        }
    else:
        test_dict = {
            "pooled": {"filter": {}, "test": mode, "ref": ref, "pairs": pair_list or []},
        }
        



    ### Information about tests going to be run ###
    # inform the user which groups are availabel for testing
    status.ok(f"Stats will be conducted for the following X groups: {sel_x}")

    # Pull our names and hues
    x_label_name = _grouping_label("X")
    hue_label_name = _grouping_label("Hue")


    # Declare empty rows to write to
    rows = []

    for key, value in test_dict.items():
        status.sub(f"Conducting stats for {key}")

        filt = value.get("filter", {})
        status.ok(f"filter: {filt}")
        # unpack test
        ref_group = value.get("ref_grp")
        status.ok(f"ref_grp: {ref_group}")
        # unpack ref-mode
        mode = value.get("test_mode")
        status.ok(f"Running mode: {mode}")

        # Unpack Pairs
        xg = filt.get("XGroup")
        if value.get("pairs"):
            pairs = value["pairs"]
        elif isinstance(xg, (list, tuple)) and len(xg) == 2:
            pairs = [tuple(xg)]                 # e.g. [("WT", "HOM/HEMI")]
        else:
            pairs = []
        status.ok(f"Pair List: {pairs}")


        ### Run the stats ###
        # iterate over dict of dict
        
        for metric in metric_cols:

            # Adjust dfm
            dfm = long_df[(long_df["variable"] == metric) & (long_df["XGroup"].isin(sel_x))].copy()

            # Apply THIS test's filter (empty filter = pooled, no-op).
            for col, val in filt.items():
                dfm = dfm[dfm[col].isin(val)] if isinstance(val, (list, tuple, set)) \
                      else dfm[dfm[col] == val]



            dfm = dfm.dropna(subset=["value"])

            if dfm.empty:
                continue



            stats = _twoway_anova_full(dfm)
            subjects = _subjects_n_per_group(dfm)

            if not stats.get("ok", False):
                rows.append({
                    "Comparison": key,
                    "Figure": metric,
                    "Test": "ANOVA failed",
                    "Subjects": subjects,
                    "F value interaction": "n/a",
                    "p value interaction": "n/a",
                    "Partial eta squared interaction": "n/a",
                    "Main effects": stats.get("err", "unknown error"),
                    "Partial eta squared main effects": "n/a",
                    "Post hoc test": "n/a",
                    "Post hoc results": "n/a",
                })
                continue

            if stats["test"] == "Two-way ANOVA":
                main_effects = (
                    f"{x_label_name}: {_fmt_F(stats['df_x_num'], stats['df_x_den'], stats['F_x'])}, "
                    f"p={_fmt_p_num(stats['p_x'])} {_p_to_stars(stats['p_x'])}; "
                    f"{hue_label_name}: {_fmt_F(stats['df_h_num'], stats['df_h_den'], stats['F_h'])}, "
                    f"p={_fmt_p_num(stats['p_h'])} {_p_to_stars(stats['p_h'])}"
                )
                main_effect_sizes = (
                    f"{x_label_name}: "
                    f"partial η²={_fmt_eta_p2(stats['eta_p_x'])}; "
                    f"{hue_label_name}: "
                    f"partial η²={_fmt_eta_p2(stats['eta_p_h'])}"
                )

                f_int = _fmt_F(stats["df_int_num"], stats["df_int_den"], stats["F_int"])
                p_int = _fmt_p_num(stats["p_int"]) + (f" {_p_to_stars(stats['p_int'])}" if np.isfinite(stats["p_int"]) else "")

                if np.isfinite(stats["p_int"]):
                    stars = _p_to_stars(stats["p_int"])
                    if stars:
                        p_int += f" {stars}" 
                eta_p_int = _fmt_eta_p2(
                    stats["eta_p_int"]
                )
            else:
                main_effects = (
                    f"{x_label_name}: {_fmt_F(stats['df_x_num'], stats['df_x_den'], stats['F_x'])}, "
                    f"p={_fmt_p_num(stats['p_x'])} {_p_to_stars(stats['p_x'])}"
                )
                #f_int, p_int = "n/a", "n/a"
                main_effect_sizes = (
                    f"{x_label_name}: "
                    f"partial η²={_fmt_eta_p2(stats['eta_p_x'])}"
                )
                f_int, p_int, eta_p_int = "n/a", "n/a", "n/a"

            if mode == "ref":
                posthoc_test = "Unpaired t-tests vs reference"
                posthoc_res  = _posthoc_ref_ttests(dfm, ref_group)
            else:
                posthoc_test = "Selected pairwise ANOVA"
                posthoc_res  = _posthoc_pairs_anova(dfm, pair_list or [], x_label_name, hue_label_name)

            rows.append({
                "Comparison": key,
                "Figure": metric,
                "Test": stats["test"],
                "Subjects": subjects,
                "F value interaction": f_int,
                "p value interaction": p_int,
                "Partial eta squared interaction": eta_p_int,
                "Main effects": main_effects,
                "Partial eta squared main effects": main_effect_sizes,
                "Post hoc test": posthoc_test,
                "Post hoc results": posthoc_res,
            })

    # change list to dataframe
    stats_df = pd.DataFrame(rows)


    
    ### Prepare to write ###
    # Grab example row
    example = long_df.iloc[0]

    # Grab the strain number
    strain_num_raw = example.get("Gene_ID", example.get("Strain_ID", "NA"))
    try:
        strain_num = f"{int(strain_num_raw):03d}"
    except Exception:
        strain_num = str(strain_num_raw).zfill(3)

    # grab the task name
    task_name = str(example.get("Session_type", "Unknown")).replace(" ", "_")

    # grab the strain name
    strain_name = str(example.get("Gene", example.get("Strain", "NA"))).replace(" ", "_")

    # pull the name together
    fname = f"{strain_name}_{strain_num}_{task_name}_stats_table.csv"
    out_path = out_dir / fname
    
    # write stats table
    stats_df.to_csv(out_path, index=False)

    ### Return ###
    status.ok("Stats table built")

    return stats_df



