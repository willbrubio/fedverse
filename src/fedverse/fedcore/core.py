def _basename(pathlike) -> str:
    """
    Is called by build_metakey as well as other functions throughout 
    Argument:
        pathlike; string
            string of path
    Returns:
        basename from a path
    """
    s = str(pathlike).replace("\\", "/")
    return s.split("/")[-1]

def _clean_colname(c):
    """
    Cleans column name, called typiclly within a loop to clean all columnnames 
    Called by:
        build_metakey
    Argument:
        c; string
            string of column name
    """
    c = str(c).strip()
    c = c.replace("$", "")
    c = re.sub(r"\s+", "_", c)
    c = re.sub(r"_+", "_", c)
    return c




