def get_cols(assay, kind, status):
    """Validate `assay` and return the requested column list for it.

    `kind` is "meta", "metric", etc. Returns a *copy* so callers can trim or
    extend the list per-function without mutating the shared ASSAY_COLS.
    """
    # User-facing validation: assay came from the caller/user, so fail gracefully.
    if assay not in ASSAY_COLS:
        allowed = ", ".join(repr(a) for a in ASSAY_COLS)
        status.fail(f"Argument 'assay' needs to be one of: {allowed}.")
        # Insurance in case status.fail() is ever changed to not raise.
        raise ValueError(f"assay={assay!r} not in {allowed}")

    # Internal validation: a bad `kind` is a bug in fedverse, not user input —
    # so raise KeyError-style rather than routing it through status.fail.
    if kind not in ASSAY_COLS[assay]:
        raise KeyError(
            f"No {kind!r} columns defined for assay {assay!r}; "
            f"available kinds: {list(ASSAY_COLS[assay])}"
        )

    # Copy so per-function .append()/filtering can't poison the module-level list.
    return list(ASSAY_COLS[assay][kind])



