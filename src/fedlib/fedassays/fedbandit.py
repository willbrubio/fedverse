def compute_bandit_metrics(fed_list, md, id_col="Mouse_ID"):
    """
    Computes the metrics from the badnit tasks
    Arguments:
        fed_list; List
            List contating multiple FED Dataframes
        md; Dataframe
            meta dataframe that contatins cropped bandit key created by build_bandit_metakey   
        id_col; String, default "Mouse_ID"
            String detailing what column will serve as the key column to link both metadata and metric files
    Returns:
        Banditmetrics; Dataframe
            Dataframe containing aggragate metrics from all mice for Bandit assays
    """

    status.step("Computing Bandit metrics")

    rows = []

    for idx in tqdm.tqdm(range(len(fed_list))):
        c_df = fed_list[idx]
        file_name = _basename(getattr(c_df, "name", f"File_{idx}"))
        d, ev = _prep_events(c_df)


        if ev is None or d.empty:
            pellets = left = right = lwp = 0
            rt_med = ipi_med = pt_med = np.nan
        else:
            pellets = int((d[ev] == "Pellet").sum())
            left    = int((d[ev] == "Left").sum())
            right   = int((d[ev] == "Right").sum())
            lwp     = int((c_df[ev] == "LeftWithPellet").sum()) if ev in c_df.columns else 0

        try:
            pre_acc_all = compute_peak_accuracy(c_df)
            clean_retrieval_time = pd.to_numeric(c_df.get("Retrieval_Time", pd.Series(dtype=float)), errors="coerce")
            clean_poke_time = pd.to_numeric(c_df.get("Poke_Time", pd.Series(dtype=float)), errors="coerce")
            clean_poke_time = clean_poke_time[clean_poke_time > 0]

            # Retrieve weight from Key_Df/metadata_df
            weight_val = np.nan
            if id_col in md.columns:
                # Attempt to find the metadata row for this specific session
                # First try to match by filename if possible, then by Mouse_ID if it exists
                meta_match = md.loc[md['filename'] == file_name]
                if meta_match.empty and 'Mouse_ID' in md.columns:
                    # If we can't match filename directly, try to infer Mouse_ID from the filename
                    known_ids = md['Mouse_ID'].dropna().unique().tolist()
                    base_lower = file_name.lower()
                    hits = [mid for mid in known_ids if str(mid).lower() in base_lower]
                    if hits:
                        best_hit = max(hits, key=len)
                        meta_match = md.loc[md['Mouse_ID'] == best_hit]

                if not meta_match.empty and 'Weight5_Friday' in meta_match.columns:
                    weight_val = pd.to_numeric(meta_match['Weight5_Friday'], errors='coerce').mean()

            row = {
                "filename": file_name,
                "PeakAccuracy": pre_acc_all,
                "Total_pellets": fed3bandit_extracted.count_pellets(c_df),
                "Total_pokes": fed3bandit_extracted.count_pokes(c_df),
                "PokesPerPellet": fed3bandit_extracted.pokes_per_pellet(c_df),
                "RetrievalTime": clean_retrieval_time.median() if not clean_retrieval_time.empty else np.nan,
                "PokeTime": clean_poke_time.median() if not clean_poke_time.empty else np.nan,
                "Win-stay": compute_withinbout_win_stay(c_df),
                "Lose-shift": compute_withinbout_lose_shift(c_df),
                "Daily_Pellets": estimate_daily_pellets(c_df),
                "Inactive_Pokes": compute_inactive_pokes(c_df),
                "Active_Pokes": compute_active_pokes(c_df),
                "Left Poke with Pellet": lwp,
                "Right_Poke": right,
                "Weight": weight_val
            }
        except Exception as e:
            status.fail(f"Failed to compute OVERALL metrics for {file_name} (idx {idx}): {e}")
            continue

        try:
            day_df, night_df = _split_day_night(c_df, ts_col="MM:DD:YYYY hh:mm:ss")
            row.update({
                "PeakAccuracy_Day": compute_peak_accuracy(day_df),
                "PeakAccuracy_Night": compute_peak_accuracy(night_df),
                "Win-stay_Day": compute_withinbout_win_stay(day_df),
                "Win-stay_Night": compute_withinbout_win_stay(night_df),
                "Lose-shift_Day": compute_withinbout_lose_shift(day_df),
                "Lose-shift_Night": compute_withinbout_lose_shift(night_df),
            })
        except Exception as e:
            status.fail(f"Failed to compute DAY/NIGHT metrics for {file_name} (idx {idx}): {e}")

        rows.append(row)

    Banditmetrics = pd.DataFrame(rows)
    if Banditmetrics.empty:
        display(HTML("<b style='color:#b00'>No files to analyze.</b>"))
        raise SystemExit
    
    status.ok("metrics computed:")
    status.preview(Banditmetrics, msg="metadata key after build_bandit_metakey")

    return Banditmetrics



### ------ Attach metadata to bandit metrics ------ ###
def attach_meta_bm(bm_df, md, id_col):
    """
    Attaches cropped bandit metadata dataframe to the aggragated bandit metric dataframe

    Arguments:
        bm; Dataframe
            Dataframe containing aggragated bandit metrics for multiple mice in a Bandit assay by a FED device
        md; Dataframe
            meta dataframe that contatins cropped bandit key created by build_bandit_metakey
        id_col; String, default "Mouse_ID"
            String detailing what column will serve as the key column   
    Returns:
        bm_md; Dataframe    
            Dataframe containing aggregated metrics with metadata
    """

    status.step("Attaching metadata to bandit metrics")
    bm = bm_df.copy()

    if "filename" in md.columns and "Mouse_ID" in md.columns:
        mouse_map = md.dropna(subset=["filename"]).drop_duplicates("filename").set_index("filename")["Mouse_ID"]
        bm["Mouse_ID"] = bm["filename"].map(mouse_map)

        if bm["Mouse_ID"].isna().any():
            known_ids = md["Mouse_ID"].dropna().unique().tolist()
            for i, r in bm.loc[bm["Mouse_ID"].isna()].iterrows():
                base = _file_base_lower(r["filename"])
                hits = [mid for mid in known_ids if str(mid).lower() in base]
                if len(hits) == 1:
                    bm.at[i, "Mouse_ID"] = hits[0]
                elif len(hits) > 1:
                    longest = max(len(str(h)) for h in hits)
                    best = [h for h in hits if len(str(h)) == longest]
                    if len(best) == 1:
                        bm.at[i, "Mouse_ID"] = best[0]

    if (id_col == "Mouse_ID") and ("Mouse_ID" in bm.columns) and ("Mouse_ID" in md.columns) and bm["Mouse_ID"].notna().any():
        md_unique = md.drop_duplicates(subset=["Mouse_ID"], keep="first")
        bm_md = bm.merge(md_unique, on="Mouse_ID", how="left", suffixes=("", "_md"))
    else:
        if "filename" not in md.columns:
            raise ValueError("metadata_df has no 'filename' column, but filename is needed for this mode.")
        md_unique = md.drop_duplicates(subset=["filename"], keep="first")
        bm_md = bm.merge(md_unique, on="filename", how="left", suffixes=("", "_md"))

    status.ok("metadata attached")
    status.preview(bm_md, msg="merged bandit metric dataframe")
    return bm_md



