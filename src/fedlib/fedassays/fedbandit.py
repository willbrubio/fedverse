def _plot_metric_display(dfm, variable, ax, x_color_map, *,
                         group_order=None, hue_order=None, ylabel=None,
                         pval_fontsize=11, label_fontsize=13):
    """
    Draw ONE metric as a stripped-down bar+strip panel onto a caller-supplied
    Axes, for use in the composite L4 figure.

    Unlike _plot_metric_clean (which owns a 2-panel figure with a stats
    sidebar), this draws only the bar + individual dots + a single top-centered
    genotype p-value. It creates no figure and no per-panel legend: the caller
    (assemble_l4) supplies the Axes and builds one shared Sex legend for the
    whole figure.

    Arguments:
        dfm : DataFrame
            Long-format rows for a SINGLE metric (already filtered to `variable`),
            with columns XGroup / HueGroup / value.
        variable : str
            Metric name; used only as the y-label fallback.
        ax : matplotlib Axes
            Target axes to draw into.
        x_color_map : dict
            {XGroup -> color string} for the bars. Keys must match the (already
            relabeled) XGroup values.
        group_order : list | None
            Bar order along x. Defaults to the library's standard order.
        hue_order : list | None
            Controlled Sex order so dot colors stay consistent across panels.
        ylabel : str | None
            Y-axis label (e.g. "Total pokes"). Falls back to `variable`.

    Returns:
        handles : list[Line2D]
            Legend proxy handles for the hue (Sex) levels, so the caller can
            build a single shared legend. Empty list if fewer than 2 hue levels.
    """
    dfm = dfm.copy()

    # Bar order: caller-provided, else fall back to the library's standard order.
    order = group_order or _order_x_groups(dfm["XGroup"].dropna().unique().tolist())
    if not order:
        return []

    # Hue (Sex) order + dot colors, matching _plot_metric_clean's convention
    # (helper maps 2 hues as {hues[0]: "white", hues[1]: "black"}).
    hue_levels = hue_order or _order_hue_groups(dfm["HueGroup"].dropna().unique().tolist())
    pal_dots = _dot_palette(hue_levels)

    # --- Bars: mean per XGroup, no seaborn error bars, alpha shared with dots ---
    bar_palette = {g: x_color_map.get(g, "tab:blue") for g in order}
    sns.barplot(
        data=dfm, x="XGroup", y="value", order=order,
        hue="XGroup", legend=False, errorbar=None,
        alpha=ALPHA, ax=ax, palette=bar_palette,
    )

    # --- Individual animals as dots, colored by Sex, drawn above the bars ---
    sns.stripplot(
        data=dfm, x="XGroup", y="value", order=order,
        hue="HueGroup", hue_order=hue_levels,
        jitter=True, dodge=False, size=6,
        edgecolor="black", linewidth=1,
        palette=pal_dots, ax=ax, zorder=3, alpha=ALPHA,
    )
    # stripplot auto-attaches a legend to the axes; remove it, because the
    # composite figure carries ONE shared Sex legend built by the caller.
    if ax.legend_ is not None:
        ax.legend_.remove()

    # --- Single genotype p-value from the two-way ANOVA (matches L4 caption) ---
    # We report the XGroup (genotype) main effect p_x, NOT per-group t-tests, so
    # this reads e.g. "p = 0.002" / "p < 0.001" exactly like the deliverable.
    res = _twoway_anova_full(dfm)
    if res.get("ok") and np.isfinite(res.get("p_x", np.nan)):
        ax.text(
            0.5, 1.05, _fmt_p(res["p_x"]),
            transform=ax.transAxes, ha="center", va="top",
            fontsize=pval_fontsize, fontstyle="italic",
        )

    # --- Cosmetics: no title/xlabel, metric name on y, clean spines ---
    ax.set_title("")
    ax.set_xlabel("")
    ax.set_ylabel(ylabel or variable, fontsize=label_fontsize)
    sns.despine(ax=ax)

    # Build (but do NOT place) the Sex legend proxies for the caller to use once.
    handles = []
    if len(hue_levels) >= 2:
        handles = [
            plt.Line2D([0], [0], marker="o", linestyle="None",
                       markerfacecolor=pal_dots[h], markeredgecolor="black",
                       label=str(h))
            for h in hue_levels
        ]
    return handles


