def _plot_pleft_core(df, ax, *, line_color="dodgerblue", behaviour_label=None,
                     show_xlabel=True):
    """
    Draw ONE mouse's choice trace onto a caller-supplied Axes: the true reward
    probability for the left port (grey, the "Rewarded Side") plus the mouse's
    binned P(Left) action (colored). Creates no figure and saves nothing — the
    caller owns the Axes. This is the composable core shared by
    _plot_file_core_display (loop + save) and any composite that needs the trace.

    Arguments:
        df : DataFrame
            A single FED session, already metadata-attached and numeric-coerced.
        ax : matplotlib Axes
            Target axes to draw into.
        line_color : str
            Color for the mouse's action line. For L4 this is the GENOTYPE color
            (WT blue / gene red), not the sex color.
        behaviour_label : str | None
            Optional right-margin label, e.g. "Wildtype behaviour".
        show_xlabel : bool
            Whether to draw the "Trial" x-label (off for the top of a stack).
    """
    # True underlying reward probability for the left port (the step function).
    true_left = fed3bandit_extracted.true_probs(df, offset=5)[0]
    # Mouse's actual choice behaviour, smoothed over a sliding window.
    mouse_left = fed3bandit_extracted.binned_paction(df, window=10)

    # Grey reference = where reward actually was; colored = what the mouse did.
    ax.plot(np.arange(len(true_left)), true_left, color="black", linewidth=2, alpha=0.5)
    ax.plot(np.arange(len(mouse_left)), mouse_left, color=line_color, linewidth=3, alpha=0.7)

    ax.set_ylabel("P(Left)")
    ax.set_yticks([0, 0.5, 1])
    ax.set_xlabel("Trial" if show_xlabel else "")

    if behaviour_label:
        # Label sits just outside the right edge, colored to match the trace.
        ax.text(1.01, 0.5, behaviour_label, transform=ax.transAxes,
                va="center", ha="left", color=line_color, fontsize=12)

    sns.despine(ax=ax)


def _plot_file_core_display(fed_list, metadata_df, root_path, dpi=150,
                            select_ids=None, color_by="sex",
                            genotype_colors=None):
    """
    Plot per-file switch-bandit P(Left) traces and save them.

    L4 use: pass select_ids=[wt_id, het_id] (from find_contrast_pair) to render
    ONLY the two example mice, and color_by="genotype" so the traces match the
    rest of the figure (WT blue / gene red) instead of being colored by sex.

    Arguments:
        fed_list : list
            FED session DataFrames (each carries a .name filename attribute).
        metadata_df : DataFrame
            Stitched metadata; used to attach fields and map filename -> Mouse_ID.
        root_path : str | Path
            Output root; PNGs are written under <root_path>/indv_bandit_plots.
        dpi : int
            Save resolution.
        select_ids : list | set | None
            If given, only mice whose Mouse_ID is in this collection are plotted.
            None -> plot everything (original behaviour).
        color_by : {"sex", "genotype"}
            "sex"      -> red for female, else blue (original behaviour).
            "genotype" -> look up genotype_colors by the mouse's Genotype.
        genotype_colors : dict | None
            {Genotype -> color}, required when color_by="genotype". Keys are the
            RAW genotype labels present in the data (e.g. "WT", "HET").

    Returns:
        saved : dict
            {Mouse_ID (str) -> Path} for every trace saved, so callers can pick
            out specific mice (e.g. WT vs HET) by identity rather than order.
    """
    status.step("Beginning to plot bandit assays")

    out_dir = Path(root_path, "indv_bandit_plots")
    out_dir.mkdir(parents=True, exist_ok=True)

    # Normalize the selection to a set of strings once, for cheap membership tests.
    select_set = None if select_ids is None else {str(s) for s in select_ids}

    saved = {}  # Mouse_ID -> saved path

    for fed in fed_list:
        df = fed.copy()
        full_name = getattr(df, "name", f"File_{fed}")
        file_basename = os.path.basename(str(full_name))

        # Preserve original index once.
        if "Original_Timestamp" not in df.columns:
            df["Original_Timestamp"] = df.index

        # Attach metadata by filename (matching already done upstream).
        meta_row = None
        if "filename" in metadata_df.columns:
            mr = metadata_df.loc[metadata_df["filename"] == file_basename]
            if not mr.empty:
                meta_row = mr.iloc[0]
        if meta_row is not None:
            for col in meta_row.index:
                if col == "filename":
                    continue
                if col not in df.columns:
                    df[col] = meta_row[col]
                else:
                    if pd.isna(df[col]).all() and pd.notna(meta_row[col]):
                        df[col] = meta_row[col]

        # Resolve this file's Mouse_ID (fallback to the filename).
        mouse_id = (
            str(meta_row["Mouse_ID"])
            if (meta_row is not None and "Mouse_ID" in meta_row and pd.notna(meta_row["Mouse_ID"]))
            else file_basename
        )

        # --- Selection filter: skip mice we weren't asked to plot ---
        # Done BEFORE the expensive time/coerce/plot work so we don't waste it.
        if select_set is not None and mouse_id not in select_set:
            continue

        # Time + cleanup.
        try:
            df["timestamp"] = pd.to_datetime(df.index)
        except Exception:
            df["timestamp"] = np.arange(len(df))

        _coerce_numeric_col(df, "Poke_Time", clip_upper=2)
        _coerce_numeric_col(df, "Retrieval_Time", na_map={"Timed_out": np.nan})

        if len(df) == 0:
            status.warn(f"[!] Empty dataframe for {file_basename}. Skipping plot.")
            continue

        # --- Decide the trace color ---
        if color_by == "genotype" and genotype_colors:
            # Match the mouse's genotype (case-insensitively) to a supplied color.
            geno = str(df["Genotype"].iloc[0]).strip().upper() if "Genotype" in df.columns else ""
            # Build an upper-cased lookup so "Het"/"HET" both resolve.
            gc_upper = {str(k).upper(): v for k, v in genotype_colors.items()}
            color = gc_upper.get(geno, "dodgerblue")
        else:
            # Original behaviour: red for female, blue otherwise.
            color = "dodgerblue"
            if "Sex" in df.columns and pd.notna(df["Sex"]).any():
                try:
                    color = "red" if str(df["Sex"].iloc[0]).strip().lower().startswith("f") else "dodgerblue"
                except Exception:
                    pass

        # --- Draw via the shared core, then title + save ---
        fig, ax = plt.subplots(figsize=(10, 3))
        _plot_pleft_core(df, ax, line_color=color)
        ax.set_title(mouse_id)

        plt.tight_layout()

        safe_title = "".join(c if c.isalnum() or c in ("-", "_") else "_" for c in mouse_id)
        out_path = out_dir / f"{safe_title}_pLeft.png"
        fig.savefig(out_path, dpi=dpi, bbox_inches="tight")
        plt.close(fig)

        saved[mouse_id] = out_path
        status.ok(f"saved {out_path.name}")

    status.ok(f"Plots saved to: {out_dir}")
    return saved



