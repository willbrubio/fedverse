def _rev_learning_core(rev_df, ax, palette_map, group_order):
    """
    Draw the reverse-learning line plot (accuracy around the switch) onto a
    caller-supplied Axes. Extracted so both the standalone plot_rev_learning and
    the composite assemble_l4 can share one drawing routine.

    Assumes rev_df["Display_Group"] is ALREADY relabeled (HET -> gene name) and
    that palette_map / group_order are keyed by those final labels.
    """
    sns.lineplot(
        data=rev_df.sort_values(["Display_Group", "Timepoint"]),
        x="Timepoint", y="Value",
        hue="Display_Group", hue_order=group_order,
        palette=palette_map,
        estimator="mean", errorbar="se", n_boot=0, lw=2, ax=ax,
    )

    # Vertical dashed marker at the reversal ("Switch") point.
    ax.axvline(x=0, color="grey", linestyle=(0, (3, 5)), linewidth=1.25)

    ax.set_ylim(bottom=0, top=1)
    ymin, ymax = ax.get_ylim()
    # "Switch" caption pinned just inside the top of the plot area.
    ax.text(0.5, ymin + 0.95 * (ymax - ymin), "Switch",
            color="dimgrey", fontsize=14, ha="left", va="top", weight="bold")

    ax.set_xlabel("Trials around switch", fontsize=14)
    ax.set_ylabel("Peak Accuracy %", fontsize=14)
    ax.set_title("")
    # Genotype legend for the two lines, lower-left inside the panel.
    ax.legend(title="", frameon=False, loc="lower left", borderaxespad=0.2)
    sns.despine(ax=ax)


