def _fed_for_mouse(fed_list, metadata_df, mouse_id):
    """
    Return the FIRST FED session DataFrame whose filename maps (via metadata_df)
    to `mouse_id`, or None if not found. Used by Option 2 above to draw a mouse's
    trace directly rather than re-reading a saved PNG.

    Note: a mouse may have several sessions; this returns the first match. Pick a
    specific session upstream if you need a particular one.
    """
    if "Mouse_ID" not in metadata_df.columns or "filename" not in metadata_df.columns:
        return None
    # All filenames belonging to this mouse.
    files = set(
        metadata_df.loc[metadata_df["Mouse_ID"].astype(str) == str(mouse_id), "filename"]
    )
    if not files:
        return None
    for fed in fed_list:
        name = os.path.basename(str(getattr(fed, "name", "")))
        if name in files:
            return fed
    return None






